#!/usr/bin/env python3
"""Generate src/pg18_joinsearch.c from PostgreSQL's own source at a release tag.

    python tools/gen_pg18_joinsearch.py REL_18_4 [--src DIR]

PostgreSQL 18 builds a join relation and its paths in one call
(`make_join_rel` -> `populate_joinrel_with_paths`, the latter static), so an
extension that must set a join's row estimate BEFORE its paths are built, or
restrict the join method per (outer, inner) pair, has to run its own copy of
the join search. This script makes that copy mechanical:

  * the functions below are taken VERBATIM from the tag's joinrels.c and
    allpaths.c, comments included;
  * the only edits are the renames and the two insertion points listed in
    EDITS, each of which must match exactly once or the script fails;
  * the partitionwise-join call is removed. vg_planner falls through to core
    whenever enable_partitionwise_join is on.

Moving the pin (a new 18.x minor) means: rerun with the new tag, review the
diff of src/pg18_joinsearch.c, rebuild, rerun the regression suite including
the core-equivalence test. Never hand-edit the generated file.
"""
import argparse
import os
import re
import sys
import urllib.request

RAW = "https://raw.githubusercontent.com/postgres/postgres/{tag}/{path}"

JOINRELS = "src/backend/optimizer/path/joinrels.c"
ALLPATHS = "src/backend/optimizer/path/allpaths.c"

# (file, function) in output order. Statics stay static; the three entry points
# the extension calls are renamed vgp_* below.
FUNCS = [
    (ALLPATHS, "standard_join_search"),
    (JOINRELS, "join_search_one_level"),
    (JOINRELS, "make_rels_by_clause_joins"),
    (JOINRELS, "make_rels_by_clauseless_joins"),
    (JOINRELS, "join_is_legal"),
    (JOINRELS, "make_join_rel"),
    (JOINRELS, "populate_joinrel_with_paths"),
    (JOINRELS, "has_join_restriction"),
    (JOINRELS, "restriction_is_constant_false"),
]

RENAMES = [
    (r"\bstandard_join_search\b", "vgp_standard_join_search"),
    (r"\bjoin_search_one_level\b", "vgp_join_search_one_level"),
    (r"\bmake_join_rel\b", "vgp_make_join_rel"),
    (r"\bpopulate_joinrel_with_paths\b", "vgp_populate_joinrel_with_paths"),
    (r"\bmake_rels_by_clause_joins\b", "vgp_make_rels_by_clause_joins"),
    (r"\bmake_rels_by_clauseless_joins\b", "vgp_make_rels_by_clauseless_joins"),
]

# (pattern, replacement, expected count)
EDITS = [
    # Insertion point 1: the joinrel exists and is sized; no path exists yet.
    (r"(\tjoinrel = build_join_rel\(root, joinrelids, rel1, rel2,\n"
     r"\t\t\t\t\t\t\t sjinfo, pushed_down_joins,\n"
     r"\t\t\t\t\t\t\t &restrictlist\);\n)",
     r"\1\n\t/* VG_PLANNER INSERTION POINT 1: join size, order rule */\n"
     r"\tvgp_joinrel_built(root, joinrel, rel1, rel2);\n", 1),
    # Insertion point 2: every (outer, inner) pair goes through the wrapper.
    (r"\badd_paths_to_joinrel\(", "VGP_ADD_PATHS_TO_JOINREL(", 12),
    # No partitionwise join in the copy (see the module comment).
    (r"\t/\* Apply partitionwise join technique, if possible\. \*/\n"
     r"\ttry_partitionwise_join\(root, rel1, rel2, joinrel, sjinfo, restrictlist\);\n",
     "\t/* VG_PLANNER: try_partitionwise_join omitted (vg_planner falls\n"
     "\t * through to core when enable_partitionwise_join is on). */\n", 1),
]

HEADER = """\
/*-------------------------------------------------------------------------
 *
 * pg18_joinsearch.c
 *	  vg_planner's copy of PostgreSQL's dynamic-programming join search.
 *
 * GENERATED by tools/gen_pg18_joinsearch.py from PostgreSQL {tag}
 * (src/backend/optimizer/path/joinrels.c, allpaths.c). DO NOT EDIT BY HAND:
 * rerun the generator and review the diff.
 *
 * The function bodies are core's, verbatim, apart from:
 *	  - renames to vgp_* for the entry points;
 *	  - VG_PLANNER INSERTION POINT 1 after build_join_rel (advice_rules.c);
 *	  - VGP_ADD_PATHS_TO_JOINREL around every add_paths_to_joinrel call
 *	    (insertion point 2, advice_rules.c);
 *	  - try_partitionwise_join removed.
 *
 * Portions Copyright (c) 1996-2025, PostgreSQL Global Development Group
 * Portions Copyright (c) 1994, Regents of the University of California
 * (PostgreSQL License)
 *
 *-------------------------------------------------------------------------
 */
#include "postgres.h"

#include "miscadmin.h"
#include "optimizer/appendinfo.h"
#include "optimizer/joininfo.h"
#include "optimizer/pathnode.h"
#include "optimizer/paths.h"
#include "partitioning/partbounds.h"
#include "utils/memutils.h"

#include "vg_planner.h"

{prototypes}
static void vgp_join_search_one_level(PlannerInfo *root, int level);
static RelOptInfo *vgp_make_join_rel(PlannerInfo *root, RelOptInfo *rel1,
									 RelOptInfo *rel2);

"""


def fetch(tag, path, src):
    if src:
        with open(os.path.join(src, path)) as f:
            return f.read()
    with urllib.request.urlopen(RAW.format(tag=tag, path=path)) as r:
        return r.read().decode()


def extract(text, name):
    """The function `name` (definition at column 0) with its leading comment."""
    lines = text.split("\n")
    starts = [i for i, l in enumerate(lines) if re.match(rf"^{name}\(", l)]
    if len(starts) != 1:
        sys.exit(f"{name}: {len(starts)} definitions found")
    i = starts[0]
    # return type line(s) above the name
    j = i - 1
    while j >= 0 and lines[j] and not lines[j].startswith(("/*", " *", "}")) \
            and not lines[j].endswith("*/"):
        j -= 1
    # leading block comment
    k = j
    if k >= 0 and lines[k].endswith("*/"):
        while k >= 0 and not lines[k].startswith("/*"):
            k -= 1
    else:
        k = j + 1
    end = i
    while lines[end] != "}":
        end += 1
    return "\n".join(lines[k:end + 1])


def prototypes(text, names):
    """The tag's own `static` prototypes for the copied functions, verbatim."""
    out = []
    for m in re.finditer(r"^static [^;{]*?\b(\w+)\([^;{]*?\);\n", text, re.M | re.S):
        if m.group(1) in names:
            out.append(m.group(0))
    missing = set(names) - {re.search(r"\b(\w+)\(", p).group(1) for p in out}
    for name in sorted(missing):
        # Core defines it before its first use and so declares no prototype;
        # ours is called earlier, so derive one from the definition's header.
        m = re.search(rf"^static ([^\n]*)\n({name}\([^{{]*?\))\n\{{", text, re.M | re.S)
        if not m:
            sys.exit(f"no static prototype or definition header for {name}")
        out.append(f"static {m.group(1)} {m.group(2)};\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tag")
    ap.add_argument("--src", help="a PostgreSQL source tree at that tag (else GitHub)")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src",
                                                  "pg18_joinsearch.c"))
    a = ap.parse_args()
    files = {p: fetch(a.tag, p, a.src) for p in {JOINRELS, ALLPATHS}}
    body = "\n\n".join(extract(files[p], n) for p, n in FUNCS)
    statics = [n for p, n in FUNCS if p == JOINRELS and re.search(
        rf"^static [^;{{]*?\b{n}\(", files[JOINRELS], re.M | re.S)]
    protos = prototypes(files[JOINRELS], statics)
    for pat, rep in RENAMES:
        protos = re.sub(pat, rep, protos)
    for pat, rep in RENAMES:
        body = re.sub(pat, rep, body)
    for pat, rep, want in EDITS:
        body, n = re.subn(pat, rep, body)
        if n != want:
            sys.exit(f"edit {pat[:50]!r}: matched {n}, expected {want}. "
                     "Core changed here; review before re-pinning.")
    # standard_join_search is extern in core; ours is the extension's entry.
    body = body.replace("RelOptInfo *\nvgp_standard_join_search(", "RelOptInfo *\nvgp_standard_join_search(", 1)
    # join_search_one_level / make_join_rel are extern in core; ours are static.
    body = body.replace("void\nvgp_join_search_one_level(", "static void\nvgp_join_search_one_level(", 1)
    body = body.replace("RelOptInfo *\nvgp_make_join_rel(", "static RelOptInfo *\nvgp_make_join_rel(", 1)
    with open(a.out, "w") as f:
        f.write(HEADER.format(tag=a.tag, prototypes=protos) + body + "\n")
    print(f"wrote {os.path.normpath(a.out)} from {a.tag}")


if __name__ == "__main__":
    main()
