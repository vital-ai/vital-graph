# ---------------------------------------------------------------------------
# Query construction — shared so a bench and a correctness test walk the graph
# the same way
# ---------------------------------------------------------------------------

def frame_hop(n: int, from_var: str, to_var: str, criterion: str = "") -> str:
    """One entity -> frame -> entity hop as its own 6 tables.

    Both slot values stay VARIABLES. `rewrite_frame_entity_table` reads the
    entity from the object variable, so an end pinned to a constant is not
    recognised as a slot group and that hop does not collapse (issues/048).
    Pin the start with FILTER instead.

    `criterion` is a template using {n}: anything it binds must be numbered per
    hop, or one value has to satisfy every hop at once and the query returns
    empty for a reason that has nothing to do with the data.
    """
    return f"""
        ?f{n} a <{HALEY}KGFrame> .
        ?se{n} <{VITAL}hasEdgeSource> ?f{n} .
        ?se{n} <{VITAL}hasEdgeDestination> ?ss{n} .
        ?ss{n} <{HALEY}hasKGSlotType> <{SRC_ROLE}> .
        ?ss{n} <{HALEY}hasEntitySlotValue> {from_var} .
        ?de{n} <{VITAL}hasEdgeSource> ?f{n} .
        ?de{n} <{VITAL}hasEdgeDestination> ?ds{n} .
        ?ds{n} <{HALEY}hasKGSlotType> <{DST_ROLE}> .
        ?ds{n} <{HALEY}hasEntitySlotValue> {to_var} .{criterion.format(n=n)}"""


def relation_hop(n: int, from_var: str, to_var: str, criterion: str = "") -> str:
    """One entity -> entity hop over Edge_hasKGRelation.

    The other traversal shape: no frame, no slots, so `frame_entity` cannot
    apply and the edge table is what has to carry it.
    """
    return f"""
        ?r{n} a <{HALEY}Edge_hasKGRelation> .
        ?r{n} <{VITAL}hasEdgeSource> {from_var} .
        ?r{n} <{VITAL}hasEdgeDestination> {to_var} .{criterion.format(n=n)}"""


def chain_query(fx: GraphFixture, start: int, depth: int, *,
                criterion: str = "", hop=frame_hop) -> str:
    """Follow `depth` hops from `start`, projecting the far end."""
    hops = "".join(hop(i + 1, f"?e{i}", f"?e{i + 1}", criterion)
                   for i in range(depth))
    return f"""
    SELECT DISTINCT ?e{depth} WHERE {{ GRAPH <{fx.graph}> {{
        {hops}
        FILTER(?e0 = <{fx.entity_uri(start)}>)
    }} }}"""


# Criterion templates, one per datatype. Each is paired with the manifest key
# holding the answers for that same filter, so a test cannot compare a query
# against the wrong ground truth.
CRITERIA = {
    "score_gte_50": (
        f'\n        ?f{{n}} <{SCORE}> ?sc{{n}} . FILTER(?sc{{n}} >= 50)',
        "frame_traversal_score_gte_50"),
    "category_in_alpha_beta": (
        f'\n        ?f{{n}} <{CATEGORY}> ?ct{{n}} . '
        f'FILTER(?ct{{n}} IN ("alpha", "beta"))',
        "frame_traversal_category_in_alpha_beta"),
    "occurred_second_half": (
        f'\n        ?f{{n}} <{OCCURRED}> ?oc{{n}} . '
        f'FILTER(?oc{{n}} >= "2024-07-01T00:00:00+00:00"'
        f'^^<http://www.w3.org/2001/XMLSchema#dateTime>)',
        "frame_traversal_occurred_second_half"),
}


def entity_indexes(rows) -> set:
    """Entity INDEXES from result rows, whatever the generated column names are."""
    prefix = f"{BASE}:entity:"
    out = set()
    for r in rows:
        for v in r.values():
            if isinstance(v, str) and v.startswith(prefix):
                out.add(int(v[len(prefix):]))
    return out
